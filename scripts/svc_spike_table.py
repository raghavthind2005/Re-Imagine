"""Summarise SVC spike measurements into a table.

python scripts/svc_spike_table.py runs/.../svc_spike/results.jsonl --out results/svc_spike
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    rows = [json.loads(line) for line in Path(args.results).read_text().splitlines()]
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    kept = [{k: v for k, v in r.items() if k != "error_tail"} for r in rows]
    (out / "results.jsonl").write_text("\n".join(json.dumps(r) for r in kept) + "\n")

    lines = [
        "<!-- Generated by scripts/svc_spike_table.py. Do not edit by hand. -->",
        "",
        "| Variant | Image | Move | Ran | Precision | Size | Frames/pass | Steps | Views "
        "| s/view | Peak VRAM (GB) |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        v = r["variant"]
        ran = "yes" if r["ok"] else ("no (OOM)" if r.get("oom") else "no")
        lines.append(
            f"| {v['name']} | {Path(r['image']).stem} | {r['traj_prior']} | {ran} | {v['dtype']} "
            f"| {v['H']} | {v['T']} | {v['num_steps']} | {r.get('n_views', '')} "
            f"| {r.get('seconds_per_view', '')} | {r.get('peak_vram_gb', '')} |"
        )
    gpus = sorted({r["gpu"] for r in rows if r.get("gpu")})
    lines += ["", f"GPU: {', '.join(gpus)}. n = {len(rows)} runs.", ""]
    (out / "table.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
