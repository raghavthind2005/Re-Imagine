"""Tables for the pre-registered downstream check (docs/PREREGISTRATION.md, section 2).

    python scripts/downstream_table.py --vsi runs/x/downstream_vsi100 --sat runs/x/downstream_sat97 \\
        --out results/downstream.md
"""

# ruff: noqa: E501  (long table-row strings)
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from mindseye.eval.metrics import bootstrap_ci
from mindseye.eval.selective import aurc, confident_error_rate, paired_bootstrap_diff

MODES = ("vlm_only", "imagine", "imagine_visa", "imagine_ours")
NAMES = {
    "vlm_only": "`vlm_only`",
    "imagine": "`imagine` (both imagined views)",
    "imagine_visa": "`imagine` + self-check filter (ViSA-style)",
    "imagine_ours": "`imagine` + map filter (ours)",
}
HIGH = 0.9


def load(d: Path) -> dict[str, dict[str, dict]]:
    out = {}
    for m in MODES:
        rows = [
            json.loads(line) for line in (d / f"predictions_{m}.jsonl").read_text().splitlines()
        ]
        out[m] = {r["id"]: r for r in rows}
    ids = set.intersection(*(set(v) for v in out.values()))
    return {m: {i: out[m][i] for i in sorted(ids)} for m in MODES}


def fmt(x: float, lo: float, hi: float, signed: bool = False) -> str:
    f = "{:+.1f}" if signed else "{:.1f}"
    return f"{f.format(100 * x)} ({f.format(100 * lo)} to {f.format(100 * hi)})"


def section(title: str, P: dict, key: str, cluster: bool) -> list[str]:
    ids = list(P["vlm_only"])
    clusters = [P["vlm_only"][i]["scene"] for i in ids] if cluster else None
    L = [
        f"## {title}",
        "",
        f"Questions: {len(ids)}; intervals: 95%, {'scene' if cluster else 'question'}-level bootstrap.",
        "",
    ]
    L += [
        "| Mode | Score | vs `vlm_only` | vs `imagine` | Imagined views used (mean) |",
        "|---|---|---|---|---|",
    ]
    for m in MODES:
        s = np.array([P[m][i][key] for i in ids], float)
        lo, hi = bootstrap_ci(lambda idx, s=s: float(s[idx].mean()), len(s), clusters=clusters)
        cells = [fmt(s.mean(), lo, hi)]
        for ref in ("vlm_only", "imagine"):
            if m == ref:
                cells.append("—")
                continue
            r = np.array([P[ref][i][key] for i in ids], float)
            d = paired_bootstrap_diff(s, r, clusters=clusters)
            cells.append(fmt(d["diff"], d["ci_low"], d["ci_high"], True))
        views = np.mean([P[m][i]["n_imagined_views"] for i in ids])
        L.append(f"| {NAMES[m]} | " + " | ".join(cells) + f" | {views:.2f} |")
    mca = [i for i in ids if P["vlm_only"][i]["confidence"] is not None]
    L += [
        "",
        f"Multiple-choice questions (confidence = probability of the chosen option; high = ≥ {HIGH}): {len(mca)}.",
        "",
    ]
    L += [
        "| Mode | Confident-error rate | High-confidence answers | AURC (lower is better) |",
        "|---|---|---|---|",
    ]
    for m in MODES:
        correct = np.array([P[m][i]["score"] == 1.0 for i in mca])
        conf = np.array([P[m][i]["confidence"] for i in mca], float)
        high = conf >= HIGH
        cl = [P[m][i]["scene"] for i in mca] if cluster else None
        cer = confident_error_rate(correct, high)
        try:
            lo, hi = bootstrap_ci(
                lambda idx, c=correct, h=high: confident_error_rate(c[idx], h[idx]),
                len(mca),
                clusters=cl,
            )
            cer_s = fmt(cer, lo, hi)
        except ValueError:
            cer_s = "n/a" if np.isnan(cer) else f"{100 * cer:.1f} (interval n/a)"
        L.append(
            f"| {NAMES[m]} | {cer_s} | {int(high.sum())} of {len(mca)} | {aurc(correct, conf):.3f} |"
        )
    return L + [""]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--vsi", required=True)
    ap.add_argument("--sat", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    V, S = load(Path(args.vsi)), load(Path(args.sat))
    L = [
        "<!-- Generated by scripts/downstream_table.py. Do not edit by hand. -->",
        "",
        "Pre-registered in `docs/PREREGISTRATION.md`, section 2. Qwen3-VL-8B; imagined views reused "
        "from the 'always top 2' runs; a view is kept by a filter only if it shows at least one "
        "object and every object passes the check.",
        "",
    ]
    L += section("VSI-Bench dev, 100 questions (mean score)", V, "score", True)
    L += section("SAT perspective dev, 97 questions, strict circular", S, "score", False)
    L += section("SAT perspective dev, 97 questions, order-averaged", S, "score_avg", False)
    # Pre-registered success check.
    verdict = []
    for name, P, key, cl in (("VSI-Bench", V, "score", True), ("SAT strict", S, "score", False)):
        ids = list(P["vlm_only"])
        clusters = [P["vlm_only"][i]["scene"] for i in ids] if cl else None
        d = paired_bootstrap_diff(
            [P["imagine_ours"][i][key] for i in ids],
            [P["vlm_only"][i][key] for i in ids],
            clusters=clusters,
        )
        not_worse = d["diff"] >= -0.01 and d["ci_high"] > 0
        mca = [i for i in ids if P["vlm_only"][i]["confidence"] is not None]

        def cer(m, mca=mca, P=P):
            return confident_error_rate(
                [P[m][i]["score"] == 1.0 for i in mca], [P[m][i]["confidence"] >= HIGH for i in mca]
            )

        lower = cer("imagine_ours") < cer("imagine")
        verdict.append(f"- {name}: not worse than `vlm_only`: {'yes' if not_worse else 'no'} ({fmt(d['diff'], d['ci_low'], d['ci_high'], True)}); "
                       f"confident-error rate below `imagine`: {'yes' if lower else 'no'} ({100 * cer('imagine_ours'):.1f} vs {100 * cer('imagine'):.1f}).")  # fmt: skip
    L += ["## Pre-registered success check", "", *verdict, ""]
    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
