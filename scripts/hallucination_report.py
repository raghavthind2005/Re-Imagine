"""Report for the scaled hallucination measurement and the self-verification baseline.

    python scripts/hallucination_report.py --objects runs/x/heldout_objects \\
        --judgements runs/x/heldout_vlm/judgements.jsonl --out results/hallucination_v2.md

All intervals resample whole scenes (cluster bootstrap), 2,000 resamples.
"""

# ruff: noqa: E501  (long table-row strings)
from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from collections.abc import Callable
from pathlib import Path

import numpy as np

from mindseye.eval.hallucination import cohen_kappa, flag_metrics

N_BOOT = 2000


def scene_boot(rows: list[dict], stat: Callable[[list[dict]], float], seed: int = 0):
    """Point estimate and 95% interval of ``stat(rows)``, resampling scenes."""
    point = stat(rows)
    by_scene: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_scene[r["scene"]].append(r)
    groups = [by_scene[k] for k in sorted(by_scene)]
    rng = np.random.default_rng(seed)
    vals = []
    for _ in range(N_BOOT):
        picked = [x for g in rng.integers(0, len(groups), len(groups)) for x in groups[g]]
        val = stat(picked)
        if not np.isnan(val):
            vals.append(val)
    if np.isnan(point) or len(vals) < 0.9 * N_BOOT:
        return point, None
    lo, hi = np.quantile(vals, [0.025, 0.975])
    return point, (float(lo), float(hi))


def pct(est, signed: bool = False) -> str:
    point, ci = est
    if np.isnan(point):
        return "n/a"
    f = "{:+.0f}" if signed else "{:.0f}"
    if ci is None:
        return f.format(100 * point) + "% (interval n/a)"
    return f"{f.format(100 * point)}% ({f.format(100 * ci[0])} to {f.format(100 * ci[1])})"


def ratio(num: str, den: str) -> Callable[[list[dict]], float]:
    def stat(rows: list[dict]) -> float:
        d = sum(r[den] for r in rows)
        return sum(r[num] for r in rows) / d if d else float("nan")

    return stat


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--objects", required=True)
    ap.add_argument("--judgements")
    ap.add_argument("--context")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    views = []
    for f in sorted(Path(args.objects).glob("views*.jsonl")):
        views += [json.loads(line) for line in f.read_text().splitlines()]
    for v in views:
        v["n_inv"], v["n_imag"] = len(v["invented"]), len(v["imagined_labels"])
        v["n_miss"], v["n_real"] = len(v["missing"]), len(v["real_labels"])
    held = [v for v in views if not v["is_control"]]
    control = [v for v in views if v["is_control"]]
    scenes = sorted({v["scene"] for v in views})

    def rate_row(name: str, rows: list[dict]) -> str:
        if not rows:
            return f"| {name} | 0 | | | | |"
        return (
            f"| {name} | {len(rows)} | {sum(r['n_real'] for r in rows)} "
            f"| {sum(r['n_imag'] for r in rows)} | {pct(scene_boot(rows, ratio('n_inv', 'n_imag')))} "
            f"| {pct(scene_boot(rows, ratio('n_miss', 'n_real')))} |"
        )

    def above_floor(num: str, den: str) -> Callable[[list[dict]], float]:
        def stat(rows: list[dict]) -> float:
            h = ratio(num, den)([r for r in rows if not r["is_control"]])
            c = ratio(num, den)([r for r in rows if r["is_control"]])
            return h - c

        return stat

    L = [
        "<!-- Generated by scripts/hallucination_report.py. Do not edit by hand. -->",
        "",
        f"Scenes: {len(scenes)}. Held-out views: {len(held)}. Control views: {len(control)}. "
        "Intervals are 95%, from resampling whole scenes.",
        "",
        "## 1. Imagined view against the real view of the same camera (SAM 3 labels)",
        "",
        "| Views | n views | Labels in real | Labels in imagined | Invented | Missing |",
        "|---|---|---|---|---|---|",
        rate_row("Held-out cameras (all)", held),
        rate_row("  map covers < 20% of view", [r for r in held if r["geo_coverage"] < 0.2]),
        rate_row("  map covers 20–60%", [r for r in held if 0.2 <= r["geo_coverage"] < 0.6]),
        rate_row("  map covers ≥ 60%", [r for r in held if r["geo_coverage"] >= 0.6]),
        rate_row("Control: cameras SVC was given (noise floor)", control),
        "",
        f"Held-out minus control: invented {pct(scene_boot(views, above_floor('n_inv', 'n_imag')), True)}, "
        f"missing {pct(scene_boot(views, above_floor('n_miss', 'n_real')), True)} (percentage points).",
        "",
        "Invented: share of object labels in imagined views that the real view lacks. "
        "Missing: share of the real view's labels absent from the imagined view. "
        "Control views are SVC's copies of frames it was given, so their rates are the "
        "detector's own disagreement plus SVC's reconstruction error.",
    ]

    # Claims on held-out views: one per object label the imagined view shows.
    claims = []
    for v in held:
        for c in v["claims"]:
            claims.append({**c, "scene": v["scene"], "target": v["target"]})

    L += [
        "",
        "## 2. Geometry verdicts on held-out claims (truth from SAM 3)",
        "",
        "| Claim is actually | n | Supported | Contradicted | No coverage |",
        "|---|---|---|---|---|",
    ]
    for truth, name in ((False, "Invented"), (True, "Real")):
        sub = [c for c in claims if c["true_in_real_view"] == truth]
        cnt = Counter(c["verdict"] for c in sub)
        L.append(
            f"| {name} | {len(sub)} | "
            + " | ".join(str(cnt[k]) for k in ("supported", "contradicted", "no_coverage"))
            + " |"
        )

    if args.judgements:
        J = [json.loads(line) for line in Path(args.judgements).read_text().splitlines()]
        jmap = {(j["scene"], j["target"], j["label"]): j for j in J}
        parsed = [j for j in J if j["vlm_real"] is not None]

        def agreement(rows: list[dict]) -> float:
            return float(np.mean([r["sam_real"] == r["vlm_real"] for r in rows]))

        cnt = Counter((j["sam_real"], j["vlm_real"]) for j in parsed)
        L += [
            "",
            "## 3. Second ground truth: the VLM judging the real frame",
            "",
            f"Pairs (view, label) where SAM 3 found the label in the real or the imagined view: "
            f"{len(J)}; VLM answer parsed for {len(parsed)}.",
            "",
            "| | VLM: present | VLM: absent |",
            "|---|---|---|",
            f"| SAM 3: present | {cnt[(True, True)]} | {cnt[(True, False)]} |",
            f"| SAM 3: absent | {cnt[(False, True)]} | {cnt[(False, False)]} |",
            "",
            f"Agreement {pct(scene_boot(parsed, agreement))}; Cohen's kappa "
            f"{cohen_kappa([j['sam_real'] for j in parsed], [j['vlm_real'] for j in parsed]):.2f}.",
        ]

        def vlm_invented(rows: list[dict]) -> float:
            rows = [r for r in rows if r["sam_imagined"] and r["vlm_real"] is not None]
            return float(np.mean([not r["vlm_real"] for r in rows])) if rows else float("nan")

        jh = [j for j in J if not j["is_control"]]
        jc = [j for j in J if j["is_control"]]
        L += [
            "",
            f"Invented rate with the VLM as ground truth: held-out {pct(scene_boot(jh, vlm_invented))}, "
            f"control {pct(scene_boot(jc, vlm_invented))}.",
        ]

        # Head to head.
        ctx = {}
        if args.context and Path(args.context).exists():
            for line in Path(args.context).read_text().splitlines():
                r = json.loads(line)
                ctx[(r["scene"], r["target"], r["label"])] = r["vlm_context"]
        for c in claims:
            j = jmap.get((c["scene"], c["target"], c["label"]), {})
            c["vlm_real"] = j.get("vlm_real")
            c["vlm_imagined"] = j.get("vlm_imagined")
            c["vlm_context"] = ctx.get((c["scene"], c["target"], c["label"]))
        methods = [
            ("ViSA-style: VLM on the imagined frame alone", lambda c: c["vlm_imagined"] is False),
            ("VLM on imagined frame + observed real frames", lambda c: c["vlm_context"] is False),
            ("(a) Geometry: contradicted", lambda c: c["verdict"] == "contradicted"),
            (
                "(b) Geometry: contradicted or no coverage",
                lambda c: c["verdict"] in ("contradicted", "no_coverage"),
            ),
        ]
        truths = [
            ("SAM 3 on the real frame", claims, lambda c: not c["true_in_real_view"]),
            (
                "the VLM on the real frame",
                [c for c in claims if c["vlm_real"] is not None],
                lambda c: not c["vlm_real"],
            ),
            (
                "both agree (disagreements dropped)",
                [
                    c
                    for c in claims
                    if c["vlm_real"] is not None and c["vlm_real"] == c["true_in_real_view"]
                ],
                lambda c: not c["true_in_real_view"],
            ),
        ]
        L += ["", "## 4. Head to head: flagging invented objects in imagined held-out views"]
        for tname, sub, is_inv in truths:
            n_inv = sum(is_inv(c) for c in sub)
            L += [
                "",
                f"### Ground truth: {tname}",
                "",
                f"Claims: {len(sub)}, of which invented: {n_inv}.",
                "",
                "| Method | Flagged & invented | Flagged & real | Missed invented | Passed real "
                "| Precision | Recall | F1 |",
                "|---|---|---|---|---|---|---|---|",
            ]

            def metric(flag, key, is_inv=is_inv):
                return lambda rows: flag_metrics(
                    [is_inv(c) for c in rows], [flag(c) for c in rows]
                )[key]

            for mname, flag in methods:
                m = flag_metrics([is_inv(c) for c in sub], [flag(c) for c in sub])
                cells = [
                    pct(scene_boot(sub, metric(flag, k))) for k in ("precision", "recall", "f1")
                ]
                L.append(
                    f"| {mname} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} | "
                    + " | ".join(cells)
                    + " |"
                )

            # What is left after each filter: how clean it is and how much real content survives.
            def kept_real(flag, is_inv=is_inv):
                def stat(rows):
                    kept = [c for c in rows if not flag(c)]
                    return float(np.mean([not is_inv(c) for c in kept])) if kept else float("nan")

                return stat

            def real_kept(flag, is_inv=is_inv):
                def stat(rows):
                    real = [c for c in rows if not is_inv(c)]
                    return float(np.mean([not flag(c) for c in real])) if real else float("nan")

                return stat

            L += [
                "",
                "| Filter | Claims kept | Kept claims that are real | Real claims kept |",
                "|---|---|---|---|",
            ]
            for mname, flag in [("No filter", lambda c: False)] + methods:
                kept = sum(not flag(c) for c in sub)
                L.append(
                    f"| {mname} | {kept} | {pct(scene_boot(sub, kept_real(flag)))} "
                    f"| {pct(scene_boot(sub, real_kept(flag)))} |"
                )
            visa = methods[0][1]
            L.append("")
            for mname, flag in methods[2:]:
                diffs = []
                for k in ("precision", "recall", "f1"):
                    d = scene_boot(
                        sub,
                        lambda rows, k=k, flag=flag, visa=visa: metric(flag, k)(rows)
                        - metric(visa, k)(rows),
                    )
                    diffs.append(f"{k} {pct(d, True)}")
                L.append(f"{mname} minus ViSA-style: " + ", ".join(diffs) + " (percentage points).")
        L += ["", f"Claims judged with observed-frame context: {len(ctx)} of {len(claims)}."]
        unparsed = sum(c["vlm_imagined"] is None for c in claims)
        L += [
            "",
            f"Claims with no parsed VLM answer on the imagined frame: {unparsed} (counted as not flagged).",
        ]

    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
