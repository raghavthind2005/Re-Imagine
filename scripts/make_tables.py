"""Generate results tables from raw run outputs. Tables are never edited by hand.

python scripts/make_tables.py runs/<run_id> [runs/<run_id> ...] --out results/vlm_only.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import yaml

from mindseye.eval.metrics import bootstrap_ci, mean_by_type, vsibench_overall


def load_run(run_dir: Path) -> tuple[dict, dict, list[dict]]:
    cfg = yaml.safe_load((run_dir / "config.yaml").read_text())
    env = json.loads((run_dir / "env.txt").read_text().split("\n\n# pip freeze")[0])
    preds = [json.loads(line) for line in (run_dir / "predictions.jsonl").read_text().splitlines()]
    return cfg, env, preds


def summarise(run_dir: Path, score_key: str) -> list[str]:
    cfg, env, preds = load_run(run_dir)
    scores = np.array([p[score_key] for p in preds])
    types = np.array([p["question_type"] for p in preds])
    is_vsi = cfg["data"]["benchmark"] == "vsibench"
    clusters = [p["scene"] for p in preds] if is_vsi else None

    def overall(idx: np.ndarray) -> float:
        if is_vsi:
            return vsibench_overall(scores[idx], types[idx])
        return float(scores[idx].mean())

    everything = np.arange(len(preds))
    point = overall(everything)
    lo, hi = bootstrap_ci(overall, len(preds), clusters=clusters)
    latency = [p["latency_s"] for p in preds if not p["cached"]]
    sessions_file = run_dir / "sessions.jsonl"
    vram = "n/a"
    if sessions_file.exists():
        last = json.loads(sessions_file.read_text().splitlines()[-1])
        vram = ", ".join(f"{v}" for v in last["peak_vram_gb_per_gpu"]) or "n/a"

    lines = [
        f"### {cfg['name']}",
        "",
        f"- Run: `{run_dir.name}`, commit `{env['git_commit'][:10]}`",
        f"- Config: `{cfg['config_file']}`",
        f"- Data: {cfg['data']['benchmark']} {cfg['data']['split']}, n = {len(preds)}",
        f"- Model: `{cfg['vlm'].get('model_id', cfg['vlm']['backend'])}`, view `{cfg['view']}`",
        f"- GPU: {env['gpu']}; peak VRAM per GPU (GB): {vram}",
        f"- Scorer: `{score_key}`; unparsed replies: {sum(not p['parsed'] for p in preds)}",
        (
            f"- Median latency per example: {np.median(latency):.2f} s"
            if latency
            else "- Latency: all cached"
        ),
        "",
        "| Task | n | Score | 95% CI |",
        "|---|---|---|---|",
        f"| **Overall** | {len(preds)} | **{100 * point:.1f}** | {100 * lo:.1f}–{100 * hi:.1f} |",
    ]
    for qtype, value in mean_by_type(scores, types).items():
        idx = np.flatnonzero(types == qtype)
        sub_clusters = [clusters[i] for i in idx] if clusters else None
        tlo, thi = bootstrap_ci(
            lambda j, idx=idx: float(scores[idx][j].mean()), len(idx), clusters=sub_clusters
        )
        lines.append(
            f"| {qtype} | {len(idx)} | {100 * value:.1f} | {100 * tlo:.1f}–{100 * thi:.1f} |"
        )
    return lines + [""]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+")
    ap.add_argument("--out", required=True)
    ap.add_argument(
        "--score-key", default="score", choices=["score", "score_official", "score_avg"]
    )
    args = ap.parse_args()
    lines = ["<!-- Generated by scripts/make_tables.py. Do not edit by hand. -->", ""]
    for run in args.runs:
        lines += summarise(Path(run), args.score_key)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
