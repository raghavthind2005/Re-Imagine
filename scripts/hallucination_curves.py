"""Threshold-free comparison of hallucination flagging: PR curves, AUROC, matched false-flag rates.

    python scripts/hallucination_curves.py --records results/hallucination_v2 \\
        --scores results/hallucination_v2/scores.jsonl --out results/hallucination_curves.md \\
        --figure results/figures/pr_curves.png

Continuous scores (higher = more likely invented):
- (b) coverage-aware trust: minus the share of the view's pixels where the labelled map
  shows that object, unoccluded (0 when the map does not confirm it).
- (d) ViSA-style self-check: Qwen's probability of "no" on the imagined frame alone.
- (c′) contradicted claims score 2, map-supported claims score below 0 (minus 1 minus the
  visible share), uncovered claims score Qwen's probability of "no" given the observed frames
  and the imagined frame. Thresholded at 0.5 this is the binary (c′).
Operating points at matched false-flag rates are chosen on each bootstrap resample.
"""

# ruff: noqa: E501  (long table-row strings)
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from hallucination_headtohead import load_claims
from hallucination_report import pct, scene_boot

from mindseye.eval.hallucination import flag_metrics
from mindseye.eval.ranking import auroc, average_precision, operating_points, recall_at_false_flag

VIEW_PIXELS = 384 * 512
RATES = (0.04, 0.08, 0.16)


def attach_scores(claims: list[dict], scores_path: Path) -> list[dict]:
    scores = {}
    for line in scores_path.read_text().splitlines():
        r = json.loads(line)
        scores[(r["scene"], r["target"], r["label"])] = r
    for c in claims:
        s = scores[(c["scene"], c["target"], c["label"])]
        visible = c["map_pixels_visible"] / VIEW_PIXELS
        c["score_b"] = -visible
        c["score_d"] = s["p_no_imagined"]
        if c["verdict"] == "contradicted":
            c["score_c2"] = 2.0
        elif c["verdict"] == "supported":
            c["score_c2"] = -1.0 - visible
        else:
            c["score_c2"] = s["p_no_context"]
        c["p_no_imagined"], c["p_no_context"] = s["p_no_imagined"], s["p_no_context"]
    return claims


def best_f1(labels, scores) -> float:
    """Highest F1 over all thresholds (fitted on the same data, so optimistic)."""
    vals = [
        2 * p["precision"] * p["recall"] / (p["precision"] + p["recall"])
        for p in operating_points(labels, scores)
        if p["precision"] + p["recall"] > 0
    ]
    return max(vals) if vals else float("nan")


METHODS = [
    ("(b) Coverage-aware trust", "score_b", lambda c: c["verdict"] != "supported"),
    ("(c′) Geometry + VLM with observed frames", "score_c2", lambda c: c["score_c2"] > 0.5),
    ("(d) ViSA-style self-check", "score_d", lambda c: c["vlm_imagined"] is False),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", required=True)
    ap.add_argument("--scores", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--figure")
    args = ap.parse_args()
    claims, _ = load_claims(Path(args.records))
    claims = attach_scores(claims, Path(args.scores))

    # Sanity: greedy answers against the probabilities from the same prompts.
    agree_d = np.mean([(c["p_no_imagined"] > 0.5) == (c["vlm_imagined"] is False) for c in claims])
    agree_c = np.mean(
        [
            (c["p_no_context"] > 0.5) == (c["vlm_context"] is False)
            for c in claims
            if c["vlm_context"] is not None
        ]
    )
    truths = [
        ("SAM 3 and the VLM agree (primary)",
         [c for c in claims if c["vlm_real"] is not None and c["vlm_real"] == c["true_in_real_view"]],
         lambda c: not c["true_in_real_view"]),
        ("SAM 3 alone", claims, lambda c: not c["true_in_real_view"]),
        ("VLM alone", [c for c in claims if c["vlm_real"] is not None], lambda c: not c["vlm_real"]),
    ]  # fmt: skip
    L = [
        "<!-- Generated by scripts/hallucination_curves.py. Do not edit by hand. -->",
        "",
        f"{len(claims)} object claims from imagined held-out views, 20 scenes. Intervals: 95%, "
        "2,000 scene-level bootstrap resamples. Recall at a false-flag rate: the best recall "
        "among thresholds that flag at most that share of real objects (chosen per resample). "
        "Best F1 over thresholds: threshold fitted on each resample, optimistic for every method.",
        "",
        f"Sanity check: the greedy yes/no answers match `p_no > 0.5` for {100 * agree_d:.1f}% of "
        f"self-check calls and {100 * agree_c:.1f}% of calls with observed frames.",
    ]
    curves = {}
    for ti, (tname, sub, is_inv) in enumerate(truths):

        def stat(fn, key, is_inv=is_inv):
            return lambda rows: fn([is_inv(c) for c in rows], [c[key] for c in rows])

        L += [
            "",
            f"## Ground truth: {tname}",
            "",
            f"Claims: {len(sub)}, invented: {sum(is_inv(c) for c in sub)}.",
            "",
            "| Method | AUROC | Average precision | Recall at 4% false flags | at 8% | at 16% | Best F1 over thresholds |",
            "|---|---|---|---|---|---|---|",
        ]
        for name, key, _ in METHODS:
            cells = [
                pct(scene_boot(sub, stat(auroc, key))),
                pct(scene_boot(sub, stat(average_precision, key))),
            ]
            for r in RATES:
                cells.append(
                    pct(scene_boot(sub, stat(lambda y, s, r=r: recall_at_false_flag(y, s, r), key)))
                )
            cells.append(pct(scene_boot(sub, stat(best_f1, key))))
            L.append(f"| {name} | " + " | ".join(cells) + " |")
        L += ["", "Paired differences (percentage points):", ""]
        for other in ("score_c2", "score_d"):
            oname = "(c′)" if other == "score_c2" else "(d)"
            for mname, fn in (("AUROC", auroc), ("average precision", average_precision)):
                d = scene_boot(
                    sub, lambda rows, fn=fn, o=other: stat(fn, "score_b")(rows) - stat(fn, o)(rows)
                )
                L.append(f"- (b) minus {oname}, {mname}: {pct(d, True)}")
        b_flag, c_flag = METHODS[0][2], METHODS[1][2]
        f1 = scene_boot(
            sub,
            lambda rows, inv=is_inv, bf=b_flag, cf=c_flag: flag_metrics(
                [inv(c) for c in rows], [bf(c) for c in rows]
            )["f1"]
            - flag_metrics([inv(c) for c in rows], [cf(c) for c in rows])["f1"],
        )
        L.append(f"- (b) minus (c′), F1 at the pre-registered operating points: {pct(f1, True)}")
        if ti == 0:
            curves = {
                name: (operating_points([is_inv(c) for c in sub], [c[key] for c in sub]),
                       flag_metrics([is_inv(c) for c in sub], [flag(c) for c in sub]))
                for name, key, flag in METHODS
            }  # fmt: skip
            base_rate = np.mean([is_inv(c) for c in sub])
    L += [
        "",
        "(b) has one large tie (every claim the map does not confirm scores 0), so its curve "
        "has few operating points; its recall cannot be traded down smoothly below that point.",
    ]
    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))

    if args.figure:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, ax = plt.subplots(figsize=(5.2, 4.2), dpi=150)
        for (name, (pts, binary)), color in zip(
            curves.items(), ("#1d4ed8", "#b45309", "#6b7280"), strict=True
        ):
            # Operating points only: nothing is drawn below a method's first threshold.
            r = [p["recall"] for p in pts]
            p = [p["precision"] for p in pts]
            ax.step(r, p, where="post", color=color, label=name)
            ax.plot(binary["recall"], binary["precision"], "o", color=color, ms=6)
            ax.plot(r[0], p[0], ".", color=color, ms=4)
        ax.axhline(
            base_rate,
            color="#9ca3af",
            ls=":",
            lw=1,
            label=f"Invented share ({100 * base_rate:.0f}%)",
        )
        ax.set_xlabel("Recall (invented objects flagged)")
        ax.set_ylabel("Precision")
        ax.set_xlim(0, 1)
        ax.set_ylim(0, 1.02)
        ax.set_title("Flagging world-model hallucinations (primary truth)", fontsize=9)
        ax.legend(fontsize=7, loc="lower left")
        fig.tight_layout()
        Path(args.figure).parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(args.figure)
        print("figure ->", args.figure)


if __name__ == "__main__":
    main()
