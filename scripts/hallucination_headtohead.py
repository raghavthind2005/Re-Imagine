"""Pre-registered head-to-head: flagging world-model hallucinations (docs/PREREGISTRATION.md, section 1 for dev, 3 for test).

    python scripts/hallucination_headtohead.py --records results/hallucination_v2 \\
        --out results/hallucination_headtohead.md
"""

# ruff: noqa: E501  (long table-row strings)
from __future__ import annotations

import argparse
import json
from collections.abc import Callable
from pathlib import Path

import numpy as np
from hallucination_report import pct, scene_boot

from mindseye.eval.hallucination import flag_metrics

THRESHOLDS = [round(0.05 * i, 2) for i in range(1, 20)]


def load_claims(records: Path) -> tuple[list[dict], list[dict]]:
    views = []
    for f in sorted(records.glob("views*.jsonl")):
        views += [json.loads(line) for line in f.read_text().splitlines()]
    judge = {}
    for line in (records / "judgements.jsonl").read_text().splitlines():
        j = json.loads(line)
        judge[(j["scene"], j["target"], j["label"])] = j
    ctx = {}
    for line in (records / "context.jsonl").read_text().splitlines():
        c = json.loads(line)
        ctx[(c["scene"], c["target"], c["label"])] = c["vlm_context"]
    claims = []
    for v in views:
        if v["is_control"]:
            continue
        for c in v["claims"]:
            key = (v["scene"], v["target"], c["label"])
            j = judge[key]
            claims.append(
                {
                    **c,
                    "scene": v["scene"],
                    "target": v["target"],
                    "view_coverage": v["geo_coverage"],
                    "vlm_real": j["vlm_real"],
                    "vlm_imagined": j["vlm_imagined"],
                    "vlm_context": ctx.get(key),
                }
            )
    return claims, views


def methods(t_best: float) -> list[tuple[str, Callable[[dict], bool]]]:
    def c_rule(judge: str) -> Callable[[dict], bool]:
        def flag(c: dict) -> bool:
            if c["verdict"] == "contradicted":
                return True
            if c["verdict"] == "supported":
                return False
            return c[judge] is False

        return flag

    return [
        ("(a) Geometry verdicts only", lambda c: c["verdict"] == "contradicted"),
        (
            "(b) Geometry + no-coverage rule",
            lambda c: c["verdict"] in ("contradicted", "no_coverage"),
        ),
        ("(c) Geometry where covered, VLM self-check where not", c_rule("vlm_imagined")),
        ("(c′) Geometry where covered, VLM with observed frames where not", c_rule("vlm_context")),
        ("(d) ViSA-style self-check", lambda c: c["vlm_imagined"] is False),
        (
            f"(e) Flag all claims in views with coverage < {t_best:g} (best t)",
            lambda c: c["view_coverage"] < t_best,
        ),
        ("(e) Flag all claims in views with coverage < 0.5", lambda c: c["view_coverage"] < 0.5),
    ]


def metric(flag, key: str, is_inv) -> Callable[[list[dict]], float]:
    def stat(rows: list[dict]) -> float:
        if key == "false_flag":
            real = [c for c in rows if not is_inv(c)]
            return float(np.mean([flag(c) for c in real])) if real else float("nan")
        return flag_metrics([is_inv(c) for c in rows], [flag(c) for c in rows])[key]

    return stat


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--prereg", default="section 1", help="section of docs/PREREGISTRATION.md")
    ap.add_argument("--split-name", default="20 dev scenes")
    args = ap.parse_args()
    claims, views = load_claims(Path(args.records))
    truths = [
        ("SAM 3 and the VLM agree (primary)",
         [c for c in claims if c["vlm_real"] is not None and c["vlm_real"] == c["true_in_real_view"]],
         lambda c: not c["true_in_real_view"]),
        ("SAM 3 alone", claims, lambda c: not c["true_in_real_view"]),
        ("VLM alone", [c for c in claims if c["vlm_real"] is not None], lambda c: not c["vlm_real"]),
    ]  # fmt: skip
    control = [v for v in views if v["is_control"]]
    n_inv = sum(len(v["invented"]) for v in control)
    n_imag = sum(len(v["imagined_labels"]) for v in control)
    L = [
        "<!-- Generated by scripts/hallucination_headtohead.py. Do not edit by hand. -->",
        "",
        f"Pre-registered in `docs/PREREGISTRATION.md`, {args.prereg}. {args.split_name}, "
        f"{len(claims)} object claims from imagined held-out views. Intervals: 95%, 2,000 "
        "scene-level bootstrap resamples. False-flag rate: share of real objects flagged.",
        "",
        f"SAM 3 noise floor (60 control views, cameras SVC was given): {n_inv} of {n_imag} "
        f"imagined labels ({100 * n_inv / n_imag:.0f}%) absent from the real frame.",
    ]
    verdicts = []
    for ti, (tname, sub, is_inv) in enumerate(truths):
        # The baseline's threshold is fitted on these records, per ground truth.
        f1s = {
            t: flag_metrics([is_inv(c) for c in sub], [c["view_coverage"] < t for c in sub])["f1"]
            for t in THRESHOLDS
        }
        t_best = max(THRESHOLDS, key=lambda t: (f1s[t], -t))
        M = methods(t_best)
        L += [
            "",
            f"## Ground truth: {tname}",
            "",
            f"Claims: {len(sub)}, invented: {sum(is_inv(c) for c in sub)}.",
            "",
            "| Method | Flagged | Precision | Recall | F1 | False-flag rate |",
            "|---|---|---|---|---|---|",
        ]
        for name, flag in M:
            cells = [
                pct(scene_boot(sub, metric(flag, k, is_inv)))
                for k in ("precision", "recall", "f1", "false_flag")
            ]
            L.append(f"| {name} | {sum(flag(c) for c in sub)} | " + " | ".join(cells) + " |")
        L += ["", "Paired F1 differences (percentage points):", ""]
        named = dict(M)
        d_flag, e_flag = M[4][1], M[5][1]
        wins = {}
        for ours in (
            "(b) Geometry + no-coverage rule",
            "(c) Geometry where covered, VLM self-check where not",
        ):
            ok = True
            for other_name, other in (("(d)", d_flag), ("(e) best t", e_flag)):
                est = scene_boot(
                    sub,
                    lambda rows, o=named[ours], b=other, inv=is_inv: metric(o, "f1", inv)(rows)
                    - metric(b, "f1", inv)(rows),
                )
                L.append(f"- {ours[:3]} minus {other_name}: {pct(est, True)}")
                point, ci = est
                ok &= (ci is not None and ci[0] > 0) if ti == 0 else point > 0
            wins[ours[:3]] = ok
        verdicts.append(wins)
    win = {m: verdicts[0][m] and verdicts[1][m] and verdicts[2][m] for m in ("(b)", "(c)")}
    L += [
        "",
        "## Pre-registered verdict",
        "",
        "Criterion: (b) or (c) beats both (d) and (e, best t) on F1 with the paired interval "
        "excluding 0 under the primary truth, and with positive differences under both "
        "secondary truths.",
        "",
        f"- (b): {'meets' if win['(b)'] else 'does not meet'} the criterion "
        f"(primary {verdicts[0]['(b)']}, SAM 3 {verdicts[1]['(b)']}, VLM {verdicts[2]['(b)']}).",
        f"- (c): {'meets' if win['(c)'] else 'does not meet'} the criterion "
        f"(primary {verdicts[0]['(c)']}, SAM 3 {verdicts[1]['(c)']}, VLM {verdicts[2]['(c)']}).",
        "",
        f"**Ours wins: {'yes' if any(win.values()) else 'no'}.** Two candidate methods were "
        "tested against the same baselines.",
    ]
    # Exploratory, not pre-registered: is (b) more than object-level coverage?
    _, primary, is_inv = truths[0]
    region = lambda c: c["region_covered"] < 0.5  # noqa: E731
    b_flag = methods(0.5)[1][1]
    cells = [
        pct(scene_boot(primary, metric(region, k, is_inv)))
        for k in ("precision", "recall", "f1", "false_flag")
    ]
    diff = scene_boot(
        primary, lambda r: metric(b_flag, "f1", is_inv)(r) - metric(region, "f1", is_inv)(r)
    )
    L += [
        "",
        "## Exploratory (not pre-registered)",
        "",
        "Flagging every claim whose own image region the map covers less than half "
        "(no use of object labels in the map), primary truth: precision / recall / F1 / "
        "false-flag " + " / ".join(cells) + f". (b) minus this: {pct(diff, True)} F1. "
        "Note that (b) flags every claim the labelled map does not support, so its gain over "
        "this rule comes from checking the object label against the map.",
    ]
    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
