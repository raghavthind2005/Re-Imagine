"""Answer-prior baselines computed from a run's own gold answers (no model involved).

    python scripts/chance_table.py runs/<run_id> --out results/chance.md

For each task: multiple choice -> always pick the most frequent gold letter;
numerical -> always answer the median gold value. These are upper bounds on what
a blind constant guesser could score on this exact question set, because the
constants are fitted on the same questions they are scored on.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

import numpy as np

from mindseye.eval.metrics import mean_by_type, mean_relative_accuracy, vsibench_overall


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    run = Path(args.run)
    preds = [json.loads(line) for line in (run / "predictions.jsonl").read_text().splitlines()]
    by_type: dict[str, list[dict]] = {}
    for p in preds:
        by_type.setdefault(p["question_type"], []).append(p)
    scores, types, notes = [], [], {}
    for qtype, items in sorted(by_type.items()):
        golds = [p["gold"] for p in items]
        if isinstance(golds[0], str):
            guess, _ = Counter(golds).most_common(1)[0]
            s = [float(g == guess) for g in golds]
        else:
            guess = float(np.median(golds))
            s = [mean_relative_accuracy(guess, g) for g in golds]
        notes[qtype] = guess
        scores += s
        types += [qtype] * len(s)
    is_vsi = preds[0]["benchmark"] == "vsibench"
    overall = vsibench_overall(scores, types) if is_vsi else float(np.mean(scores))
    lines = [
        "<!-- Generated by scripts/chance_table.py. Do not edit by hand. -->",
        "",
        f"### Constant-answer baseline for `{run.name}` (n = {len(preds)})",
        "",
        "| Task | n | Constant answer | Score |",
        "|---|---|---|---|",
        f"| **Overall** | {len(preds)} | | **{100 * overall:.1f}** |",
    ]
    for qtype, value in mean_by_type(scores, types).items():
        lines.append(f"| {qtype} | {len(by_type[qtype])} | {notes[qtype]} | {100 * value:.1f} |")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
