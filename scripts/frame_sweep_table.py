"""Frame-count sweep table: accuracy and geometric coverage for each K.

    python scripts/frame_sweep_table.py --geometry runs/.../geometry.jsonl \
        --run 4=runs/<a> --run 8=runs/<b> --run 16=runs/<c> --full runs/<d> \
        --out results/frame_sweep.md

Accuracy is restricted to the fixed imagination subset, so every K is scored on
the same questions. Intervals resample scenes.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from mindseye.data.splits import load_split
from mindseye.eval.metrics import bootstrap_ci
from mindseye.eval.selective import paired_bootstrap_diff


def load_preds(run: str, ids: set[str]) -> dict[str, dict]:
    lines = (Path(run) / "predictions.jsonl").read_text().splitlines()
    return {p["id"]: p for p in map(json.loads, lines) if p["id"] in ids}


def mean_ci(values: list[float], clusters: list[str] | None = None) -> str:
    arr = np.asarray(values, dtype=float)
    lo, hi = bootstrap_ci(lambda i: float(arr[i].mean()), len(arr), clusters=clusters)
    return f"{100 * arr.mean():.1f} ({100 * lo:.1f}–{100 * hi:.1f})"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--geometry", required=True)
    ap.add_argument("--run", action="append", required=True, help="K=run_dir")
    ap.add_argument("--full", help="full-video run, for the shared-question gap")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    ids = set(load_split("data/splits/imagine_subset.json")["vsi_ids"])
    geo = [json.loads(line) for line in Path(args.geometry).read_text().splitlines()]
    runs = {int(k): load_preds(r, ids) for k, r in (x.split("=", 1) for x in args.run)}
    full = load_preds(args.full, ids) if args.full else {}

    cols = [
        "K",
        "vlm_only",
        "Gap to full video",
        "Observed overlap",
        "Held-out coverage",
        "Held-out, depth-consistent",
        "Held-out views ≥50% explained",
        "VGGT s",
        "VGGT GB",
    ]
    lines = [
        "<!-- Generated by scripts/frame_sweep_table.py. Do not edit by hand. -->",
        "",
        "Scores and coverages are percentages with 95% intervals (scenes resampled).",
        "",
        "| " + " | ".join(cols) + " |",
        "|" + "---|" * len(cols),
    ]
    for k in sorted(runs):
        preds = runs[k]
        order = sorted(preds)
        acc = mean_ci([preds[i]["score"] for i in order], [preds[i]["scene"] for i in order])
        gap = "n/a"
        shared = sorted(set(preds) & set(full))
        if shared:
            d = paired_bootstrap_diff(
                [full[i]["score"] for i in shared],
                [preds[i]["score"] for i in shared],
                clusters=[preds[i]["scene"] for i in shared],
            )
            gap = (
                f"{100 * d['diff']:+.1f} ({100 * d['ci_low']:+.1f} to {100 * d['ci_high']:+.1f}),"
                f" n={len(shared)}"
            )
        rows = [g for g in geo if g["k"] == k and g["ok"]]
        failed = sum(1 for g in geo if g["k"] == k and not g["ok"])
        if rows:
            scenes = [g["scene"] for g in rows]
            cells = [
                mean_ci([g[key] for g in rows], scenes)
                for key in ("observed_overlap_consistent", "heldout_coverage",
                            "heldout_coverage_consistent", "heldout_views_half_covered")
            ]  # fmt: skip
            secs = f"{np.median([g['vggt_seconds'] for g in rows]):.1f}"
            vram = f"{max(g.get('vggt_peak_vram_gb', float('nan')) for g in rows):.1f}"
        else:
            cells, secs, vram = ["n/a"] * 4, "n/a", "n/a"
        note = f" ({failed} scenes failed)" if failed else ""
        lines.append(
            f"| {k} | {acc}, n={len(order)} | {gap} | "
            + " | ".join(cells)
            + f" | {secs} | {vram}{note} |"
        )
    n_scenes = len({g["scene"] for g in geo})
    lines += ["", f"Geometry: {n_scenes} scenes, 8 held-out views per scene.", ""]
    Path(args.out).write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
