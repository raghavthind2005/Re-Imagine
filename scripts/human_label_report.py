"""All flagging methods against the human labels of the 150-claim dev sample.

    python scripts/human_label_report.py --labels data/labels/human_labels.csv \\
        --records results/hallucination_v2 --out results/hallucination_human.md

Truth: a claim is invented if the human says the object is not visible in the real frame;
"unsure" answers are dropped. The sample is balanced by design (25 claims per SAM 3
invented/real x coverage cell), so rates here are not population rates; method
comparisons are paired on the same claims.
"""

# ruff: noqa: E501  (long table-row strings)
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np
from hallucination_curves import METHODS, attach_scores, best_f1
from hallucination_headtohead import load_claims
from hallucination_report import pct, scene_boot

from mindseye.eval.hallucination import cohen_kappa, flag_metrics
from mindseye.eval.metrics import mcnemar_exact
from mindseye.eval.ranking import auroc, average_precision


def clopper_pearson(k: int, n: int, alpha: float = 0.05) -> tuple[float, float]:
    """Exact binomial interval, by bisection on the binomial tail (no SciPy needed)."""
    from math import comb

    def tail_ge(p):  # P(X >= k)
        return sum(comb(n, i) * p**i * (1 - p) ** (n - i) for i in range(k, n + 1))

    def tail_le(p):  # P(X <= k)
        return sum(comb(n, i) * p**i * (1 - p) ** (n - i) for i in range(0, k + 1))

    def solve(f, target, increasing):
        lo, hi = 0.0, 1.0
        for _ in range(60):
            mid = (lo + hi) / 2
            if (f(mid) < target) == increasing:
                lo = mid
            else:
                hi = mid
        return (lo + hi) / 2

    lower = 0.0 if k == 0 else solve(tail_ge, alpha / 2, True)
    upper = 1.0 if k == n else solve(tail_le, alpha / 2, False)
    return lower, upper


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", required=True)
    ap.add_argument("--records", required=True)
    ap.add_argument("--sample", default="data/labels/claim_sample.json")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    claims, _ = load_claims(Path(args.records))
    claims = attach_scores(claims, Path(args.records) / "scores.jsonl")
    by_key = {f"{c['scene']}|{c['target']}|{c['label']}": c for c in claims}
    sample = json.loads(Path(args.sample).read_text())["split"]["claims"]
    with open(args.labels, newline="") as f:
        labels = {row["key"]: row for row in csv.DictReader(f)}
    rows = []
    for s in sample:
        lab = labels.get(s["key"], {})
        c = dict(by_key[s["key"]])
        c["human_real"] = lab.get("visible_in_real", "")
        c["human_imagined"] = lab.get("visible_in_imagined", "")
        c["stratum"] = s["stratum"]
        rows.append(c)
    answered = [c for c in rows if c["human_real"] in ("yes", "no")]
    is_inv = lambda c: c["human_real"] == "no"  # noqa: E731
    L = [
        "<!-- Generated by scripts/human_label_report.py. Do not edit by hand. -->",
        "",
        f"Sample: {len(sample)} claims (balanced: 25 per SAM 3 invented/real × view-coverage cell). "
        f"Labelled yes/no on the real frame: {len(answered)}; unsure or blank: {len(rows) - len(answered)}. "
        f"Invented by the human label: {sum(is_inv(c) for c in answered)}. Intervals: 95%, scene-level bootstrap.",
        "",
        "## Agreement of the automatic ground truths with the human label (real frame)",
        "",
        "| Source | Agreement | Cohen's kappa |",
        "|---|---|---|",
    ]
    for name, fn in (
        ("SAM 3", lambda c: c["true_in_real_view"]),
        ("Qwen", lambda c: c["vlm_real"] is True),
    ):
        agree = scene_boot(
            answered,
            lambda r, fn=fn: float(np.mean([fn(c) == (c["human_real"] == "yes") for c in r])),
        )
        kappa = cohen_kappa([fn(c) for c in answered], [c["human_real"] == "yes" for c in answered])
        L.append(f"| {name} | {pct(agree)} | {kappa:.2f} |")
    imag = [c for c in rows if c["human_imagined"] in ("yes", "no")]
    if imag:
        L += [
            "",
            f"Human says the claimed object is not visible in the imagined view (a SAM 3 error on "
            f"the imagined side): {sum(c['human_imagined'] == 'no' for c in imag)} of {len(imag)}.",
        ]
    L += [
        "",
        "## Methods against the human label",
        "",
        "| Method | Precision | Recall | F1 | False-flag rate | AUROC | Average precision | Best F1 over thresholds |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, key, flag in METHODS:

        def m(k, flag=flag):
            return lambda r: (
                float(np.mean([flag(c) for c in r if not is_inv(c)]))
                if k == "false_flag"
                else flag_metrics([is_inv(c) for c in r], [flag(c) for c in r])[k]
            )

        cells = [
            pct(scene_boot(answered, m(k))) for k in ("precision", "recall", "f1", "false_flag")
        ]
        for fn in (auroc, average_precision, best_f1):
            cells.append(
                pct(
                    scene_boot(
                        answered,
                        lambda r, fn=fn, key=key: fn([is_inv(c) for c in r], [c[key] for c in r]),
                    )
                )
            )
        L.append(f"| {name} | " + " | ".join(cells) + " |")
    # The second question of the sheet separates world-model hallucinations from detector
    # errors: only claims the human sees in the imagined view are genuine imagined content.
    L += [
        "",
        "## By stratum: what the SAM 3 claims actually are (human labels)",
        "",
        "| Stratum (SAM 3 truth / view coverage) | n | Not in the imagined view (detector error) | In imagined, not in real (world-model hallucination) | In both (real object) |",
        "|---|---|---|---|---|",
    ]
    for st in sorted({c["stratum"] for c in rows}):
        cs = [c for c in rows if c["stratum"] == st]
        n_det = sum(c["human_imagined"] == "no" for c in cs)
        n_hal = sum(c["human_imagined"] == "yes" and c["human_real"] == "no" for c in cs)
        n_real = sum(c["human_imagined"] == "yes" and c["human_real"] == "yes" for c in cs)
        L.append(f"| {st} | {len(cs)} | {n_det} | {n_hal} | {n_real} |")
    L += ["", "Rows do not add up to n where the human answered unsure or left a blank."]
    genuine = [c for c in answered if c["human_imagined"] == "yes"]
    L += [
        "",
        "## World-model hallucinations only (claims the human sees in the imagined view)",
        "",
        f"Claims: {len(genuine)}, of which absent from the real frame: {sum(is_inv(c) for c in genuine)}. "
        "Not pre-registered; the sheet asked both questions so that this split could be made.",
        "",
        "| Method | Flagged & hallucinated | Flagged & real | Missed hallucinations | Passed real |",
        "|---|---|---|---|---|",
    ]
    for name, _key, flag in METHODS:
        m = flag_metrics([is_inv(c) for c in genuine], [flag(c) for c in genuine])
        L.append(f"| {name} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} |")
    hal = [c for c in genuine if is_inv(c)]
    real_g = [c for c in genuine if not is_inv(c)]
    caught = {name: [flag(c) for c in hal] for name, _k, flag in METHODS}
    L += [""]
    for name, _key, flag in METHODS:
        k = sum(flag(c) for c in hal)
        lo, hi = clopper_pearson(k, len(hal))
        fk = sum(flag(c) for c in real_g)
        flo, fhi = clopper_pearson(fk, len(real_g))
        L.append(
            f"- {name}: catches {k} of {len(hal)} hallucinations ({100 * k / len(hal):.0f}%, exact 95% CI "
            f"{100 * lo:.0f}–{100 * hi:.0f}); flags {fk} of {len(real_g)} real objects "
            f"({100 * fk / len(real_g):.0f}%, {100 * flo:.0f}–{100 * fhi:.0f})."
        )
    mc = mcnemar_exact(caught[METHODS[0][0]], caught[METHODS[2][0]])
    L += [
        "",
        f"Paired on the {len(hal)} hallucinations, (b) catches {mc['only_a']} that (d) misses and (d) "
        f"catches {mc['only_b']} that (b) misses; exact McNemar p = {mc['p_value']:.4f}.",
    ]
    det = [c for c in answered if c["human_imagined"] == "no"]
    L += [
        "",
        f"Detector errors (claims the human does not see in the imagined view): {len(det)}. "
        "Share each method flags:",
        "",
    ]
    for name, _key, flag in METHODS:
        L.append(f"- {name}: {sum(flag(c) for c in det)} of {len(det)}")
    b, d = METHODS[0], METHODS[2]
    diff = scene_boot(
        answered,
        lambda r: flag_metrics([is_inv(c) for c in r], [b[2](c) for c in r])["f1"]
        - flag_metrics([is_inv(c) for c in r], [d[2](c) for c in r])["f1"],
    )
    L += ["", f"(b) minus (d), F1: {pct(diff, True)} (percentage points)."]
    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
