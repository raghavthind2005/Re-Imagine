"""Paired comparison of two runs on the questions they share.

    python scripts/compare_runs.py runs/<a> runs/<b> --out results/compare_a_vs_b.md

Reports the mean score difference (A - B) with a paired bootstrap interval
(scenes resampled together on VSI-Bench) and, for multiple-choice questions,
an exact McNemar test.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from mindseye.eval.metrics import mcnemar_exact
from mindseye.eval.selective import paired_bootstrap_diff


def load(run: Path) -> dict[str, dict]:
    lines = (run / "predictions.jsonl").read_text().splitlines()
    return {p["id"]: p for p in map(json.loads, lines)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("a")
    ap.add_argument("b")
    ap.add_argument("--out", required=True)
    ap.add_argument("--score-key", default="score")
    args = ap.parse_args()
    a, b = load(Path(args.a)), load(Path(args.b))
    ids = sorted(set(a) & set(b))
    key = args.score_key

    def row(name: str, subset: list[str]) -> str:
        sa = [a[i][key] for i in subset]
        sb = [b[i][key] for i in subset]
        clusters = [a[i]["scene"] for i in subset] if a[subset[0]]["scene"] else None
        d = paired_bootstrap_diff(sa, sb, clusters=clusters)
        mean_a, mean_b = sum(sa) / len(sa), sum(sb) / len(sb)
        cells = [name, str(len(subset)), f"{100 * mean_a:.1f}", f"{100 * mean_b:.1f}"]
        cells.append(f"{100 * d['diff']:+.1f}")
        cells.append(f"{100 * d['ci_low']:+.1f} to {100 * d['ci_high']:+.1f}")
        if all(isinstance(a[i]["gold"], str) for i in subset):
            m = mcnemar_exact([x == 1 for x in sa], [x == 1 for x in sb])
            cells.append(f"{m['only_a']} / {m['only_b']}, p = {m['p_value']:.3f}")
        else:
            cells.append("n/a")
        return "| " + " | ".join(cells) + " |"

    lines = [
        "<!-- Generated by scripts/compare_runs.py. Do not edit by hand. -->",
        "",
        f"A = `{Path(args.a).name}`  ",
        f"B = `{Path(args.b).name}`  ",
        f"Shared questions: {len(ids)} (A has {len(a)}, B has {len(b)}). Scorer: `{key}`.",
        "",
        "Scores are plain means over questions, not the task-averaged VSI-Bench aggregate.",
        "",
        "| Subset | n | A | B | A − B | 95% CI | McNemar (A only / B only) |",
        "|---|---|---|---|---|---|---|",
        row("All shared", ids),
    ]
    for qtype in sorted({a[i]["question_type"] for i in ids}):
        subset = [i for i in ids if a[i]["question_type"] == qtype]
        if len(subset) >= 10:
            lines.append(row(qtype, subset))
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
