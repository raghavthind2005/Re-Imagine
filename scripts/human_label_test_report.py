"""Pre-registered genuine-hallucination comparison on test (docs/PREREGISTRATION.md, section 4).

    python scripts/human_label_test_report.py --labels data/labels/human_labels_test.csv \\
        --out results/hallucination_human_test.md [--second data/labels/human_labels_second.csv]
"""

# ruff: noqa: E501
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
from hallucination_curves import METHODS, attach_scores
from hallucination_headtohead import load_claims
from human_label_report import clopper_pearson

from mindseye.eval.hallucination import cohen_kappa
from mindseye.eval.metrics import mcnemar_exact

ROOT = Path(__file__).resolve().parents[1]


def read(path: Path) -> dict[str, dict]:
    with open(path, newline="") as f:
        return {r["key"]: r for r in csv.DictReader(f)}


def category(lab: dict) -> str | None:
    real, imag = lab.get("visible_in_real", ""), lab.get("visible_in_imagined", "")
    if real not in ("yes", "no") or imag not in ("yes", "no"):
        return None
    if imag == "no":
        return "detector_error"
    return "hallucination" if real == "no" else "real_object"


def weighted_rate(rows: list[dict], flag, n_boot: int = 2000, seed: int = 0):
    """Weighted share flagged, with a scene-level bootstrap interval."""

    def stat(rs):
        w = np.array([r["weight"] for r in rs])
        return (
            float((w * np.array([flag(r) for r in rs])).sum() / w.sum())
            if len(rs)
            else float("nan")
        )

    by = defaultdict(list)
    for r in rows:
        by[r["scene"]].append(r)
    groups = [by[k] for k in sorted(by)]
    rng = np.random.default_rng(seed)
    vals = [
        stat([x for g in rng.integers(0, len(groups), len(groups)) for x in groups[g]])
        for _ in range(n_boot)
    ]
    lo, hi = np.nanquantile(vals, [0.025, 0.975])
    return stat(rows), float(lo), float(hi)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", required=True)
    ap.add_argument("--second")
    ap.add_argument("--sample", default=str(ROOT / "data/labels/test_claim_sample.json"))
    ap.add_argument("--records", default=str(ROOT / "results/hallucination_test"))
    ap.add_argument("--dev-labels", default=str(ROOT / "data/labels/human_labels.csv"))
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    sample = json.loads(Path(args.sample).read_text())["split"]
    labels = read(Path(args.labels))
    claims, _ = load_claims(Path(args.records))
    claims = attach_scores(claims, Path(args.records) / "scores.jsonl")
    by_key = {f"{c['scene']}|{c['target']}|{c['label']}": c for c in claims}
    flags = {name: flag for name, _k, flag in METHODS}
    B, C2, D = (m[0] for m in METHODS)

    rows = []
    for s in sample["claims"]:
        if s["group"] == "dev_repeat":
            continue
        c = dict(by_key[s["key"]])
        c.update(group=s["group"], weight=s["weight"], category=category(labels.get(s["key"], {})))
        rows.append(c)
    usable = [r for r in rows if r["category"] is not None]
    hal = [r for r in usable if r["category"] == "hallucination"]
    real = [r for r in usable if r["category"] == "real_object"]
    L = [
        "<!-- Generated by scripts/human_label_test_report.py. Do not edit by hand. -->",
        "",
        "Pre-registered in `docs/PREREGISTRATION.md`, section 4. Test scenes; primary labeller.",
        "",
        f"Test claims on the sheet: {len(rows)} (all {sum(r['group'] == 'sam3_invented_census' for r in rows)} SAM 3-invented claims; "
        f"{sum(r['group'] == 'sam3_real_sample' for r in rows)} of {sample['counts']['sam3_real']} SAM 3-real claims, weight "
        f"{sample['counts']['sam3_real'] / sample['counts']['sam3_real_sampled']:.3f}). Answered on both questions: {len(usable)}.",
        "",
        "## What the claims are",
        "",
        "| SAM 3 says | n answered | Detector error | Genuine hallucination | Real object |",
        "|---|---|---|---|---|",
    ]
    for g, name in (("sam3_invented_census", "invented"), ("sam3_real_sample", "real (sample)")):
        rs = [r for r in usable if r["group"] == g]
        L.append(
            f"| {name} | {len(rs)} | "
            + " | ".join(
                str(sum(r["category"] == k for r in rs))
                for k in ("detector_error", "hallucination", "real_object")
            )
            + " |"
        )

    L += [
        "",
        "## Primary: genuine hallucinations caught",
        "",
        f"Genuine hallucinations: {len(hal)}.",
        "",
    ]
    if len(hal) < 10:
        L += ["**Fewer than 10 genuine hallucinations: inconclusive (pre-registered rule).**", ""]
    L += ["| Method | Caught | Recall (exact 95% CI) |", "|---|---|---|"]
    for name in (B, C2, D):
        k = sum(flags[name](r) for r in hal)
        lo, hi = clopper_pearson(k, len(hal)) if hal else (float("nan"), float("nan"))
        L.append(
            f"| {name} | {k} of {len(hal)} | {100 * k / max(len(hal), 1):.0f}% ({100 * lo:.0f}–{100 * hi:.0f}) |"
        )
    verdict = "inconclusive"
    for other in (D, C2):
        mc = mcnemar_exact([flags[B](r) for r in hal], [flags[other](r) for r in hal])
        short = other.split(" ")[0]
        L.append("")
        L.append(
            f"(b) vs {short}: caught only by (b) {mc['only_a']}, only by {short} {mc['only_b']}; exact McNemar p = {mc['p_value']:.4g}."
        )
        if other == D and len(hal) >= 10:
            verdict = "met" if mc["p_value"] < 0.05 and mc["only_a"] > mc["only_b"] else "not met"
    L += [
        "",
        f"**Pre-registered criterion ((b) catches more genuine hallucinations than (d), p < 0.05): {verdict}.**",
        "",
    ]

    L += ["## False flags on real objects (weighted)", "", f"Real objects (visible in both views): {len(real)}.", "",
          "| Method | Flagged (unweighted) | Weighted false-flag rate (95% scene bootstrap) |", "|---|---|---|"]  # fmt: skip
    for name in (B, C2, D):
        k = sum(flags[name](r) for r in real)
        p, lo, hi = weighted_rate(real, flags[name])
        L.append(
            f"| {name} | {k} of {len(real)} | {100 * p:.0f}% ({100 * lo:.0f}–{100 * hi:.0f}) |"
        )

    dev = read(Path(args.dev_labels))
    reps = [s["key"] for s in sample["claims"] if s["group"] == "dev_repeat"]
    L += ["", "## Labelling consistency (30 hidden dev repeats)", ""]
    for q in ("visible_in_real", "visible_in_imagined"):
        pairs = [
            (dev[k][q], labels[k][q])
            for k in reps
            if k in labels and dev[k][q] in ("yes", "no") and labels[k][q] in ("yes", "no")
        ]
        if pairs:
            a = [x == "yes" for x, _ in pairs]
            b = [y == "yes" for _, y in pairs]
            agree = np.mean([x == y for x, y in zip(a, b, strict=True)])
            L.append(
                f"- {q.replace('_', ' ')}: {len(pairs)} answered both times, agreement {100 * agree:.0f}%, kappa {cohen_kappa(a, b):.2f}"
            )
    if args.second and Path(args.second).exists():
        sec = read(Path(args.second))
        shared = [k for k in sample["second_labeller_order"] if k in sec and k in labels]
        cats = [(category(labels[k]), category(sec[k])) for k in shared]
        cats = [(x, y) for x, y in cats if x and y]
        L += [
            "",
            "## Second labeller (50 shared test claims)",
            "",
            f"Both answered fully: {len(cats)}; same category: {100 * np.mean([x == y for x, y in cats]):.0f}%.",
        ]
        for q in ("visible_in_real", "visible_in_imagined"):
            pairs = [
                (labels[k][q], sec[k][q])
                for k in shared
                if labels[k][q] in ("yes", "no") and sec[k][q] in ("yes", "no")
            ]
            if pairs:
                a, b = [x == "yes" for x, _ in pairs], [y == "yes" for _, y in pairs]
                L.append(
                    f"- {q.replace('_', ' ')}: agreement {100 * np.mean([x == y for x, y in zip(a, b, strict=True)]):.0f}%, kappa {cohen_kappa(a, b):.2f} (n = {len(pairs)})"
                )
    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
