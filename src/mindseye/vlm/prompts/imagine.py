"""Prompts for the ``imagine`` mode (MindJourney-style search with a world model).

Bump ``VERSION`` on any wording change: it is part of every cache key.

MindJourney (arXiv 2507.12508) has the VLM give each imagined view an exploration
score and a helpfulness score; the wording here is ours.
"""

from __future__ import annotations

import re

VERSION = "imagine-v1"


def pick_start(question: str, n_frames: int) -> str:
    return (
        f"These are {n_frames} frames of a video of an indoor scene, numbered 1 to {n_frames} "
        "in order.\n"
        f"Question: {question}\n"
        "You may look around from one of these frames by moving the camera a little. Which "
        "frame is the best starting viewpoint for finding what is needed to answer the "
        "question? Answer with the frame number only."
    )


def parse_frame(text: str, n_frames: int) -> int | None:
    """Zero-based frame index from a reply, or None."""
    m = re.search(r"\d+", text)
    if not m:
        return None
    i = int(m.group()) - 1
    return i if 0 <= i < n_frames else None


def score_view(question: str, description: str) -> str:
    return (
        "You are exploring an indoor scene to answer a question.\n"
        f"Question: {question}\n"
        "The first image is a real view of the scene. The second image is an imagined view "
        f"after this camera movement from the first image: {description}.\n"
        "Rate the second image on two scales from 0 to 10:\n"
        "- exploration: how promising it is to keep moving from this view to find "
        "information needed for the question\n"
        "- helpfulness: how much this view itself helps to answer the question\n"
        "Answer in the form: exploration=<number>, helpfulness=<number>"
    )


def parse_scores(text: str) -> tuple[float, float] | None:
    e = re.search(r"exploration\D{0,5}(\d+(?:\.\d+)?)", text, re.I)
    h = re.search(r"helpfulness\D{0,5}(\d+(?:\.\d+)?)", text, re.I)
    if not (e and h):
        return None
    return min(float(e.group(1)), 10.0), min(float(h.group(1)), 10.0)


def evidence_preface(n_real: int, start: int, descriptions: list[str]) -> str:
    """Tells the model which images are real and which are imagined."""
    real = (
        f"The first {n_real} images are frames of a video."
        if n_real > 1
        else "The first image is a real photo."
    )
    origin = f"frame {start + 1}" if n_real > 1 else "the photo"
    lines = [
        real,
        f"The next {len(descriptions)} images are imagined views, generated by a model, of what "
        f"the camera would see after moving from {origin}. They may contain errors.",
    ]
    lines += [f"Imagined view {i}: {d}." for i, d in enumerate(descriptions, 1)]
    return "\n".join(lines)
